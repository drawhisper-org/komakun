/**
 * Apply a theme accent color to the document root.
 * This sets CSS custom properties for both shadcn and MD3 tokens.
 */
export function applyThemeColors(
  accentHex: string,
  resolvedTheme: "light" | "dark"
) {
  const palette = ACCENT_COLORS[accentHex];
  if (!palette) return;

  const colors = resolvedTheme === "dark" ? palette.dark : palette.light;
  const root = document.documentElement;

  // Shadcn mapped variables
  root.style.setProperty("--background", colors.background);
  root.style.setProperty("--foreground", colors.onBackground);
  root.style.setProperty("--primary", colors.primary);
  root.style.setProperty("--primary-foreground", colors.onPrimary);
  root.style.setProperty("--secondary", colors.secondary);
  root.style.setProperty("--secondary-foreground", colors.onSecondary);
  root.style.setProperty("--muted", colors.surfaceVariant);
  root.style.setProperty("--muted-foreground", colors.onSurfaceVariant);
  root.style.setProperty(
    "--accent",
    resolvedTheme === "dark" ? colors.primaryContainer : colors.primaryContainer
  );
  root.style.setProperty(
    "--accent-foreground",
    resolvedTheme === "dark"
      ? colors.onPrimaryContainer
      : colors.onPrimaryContainer
  );
  root.style.setProperty("--destructive", colors.error);
  root.style.setProperty("--destructive-foreground", colors.onError);
  root.style.setProperty(
    "--card",
    resolvedTheme === "dark" ? colors.elevation1 : colors.surface
  );
  root.style.setProperty("--card-foreground", colors.onSurface);
  root.style.setProperty(
    "--popover",
    resolvedTheme === "dark" ? colors.elevation1 : colors.surface
  );
  root.style.setProperty("--popover-foreground", colors.onSurface);
  root.style.setProperty("--border", colors.outlineVariant);
  root.style.setProperty("--input", colors.outlineVariant);
  root.style.setProperty("--ring", colors.primary);

  // MD3 extended tokens
  root.style.setProperty("--surface", colors.surface);
  root.style.setProperty("--on-surface", colors.onSurface);
  root.style.setProperty("--surface-variant", colors.surfaceVariant);
  root.style.setProperty("--on-surface-variant", colors.onSurfaceVariant);
  root.style.setProperty("--primary-container", colors.primaryContainer);
  root.style.setProperty("--on-primary-container", colors.onPrimaryContainer);
  root.style.setProperty("--secondary-container", colors.secondaryContainer);
  root.style.setProperty(
    "--on-secondary-container",
    colors.onSecondaryContainer
  );
  root.style.setProperty("--tertiary", colors.tertiary);
  root.style.setProperty("--on-tertiary", colors.onTertiary);
  root.style.setProperty("--tertiary-container", colors.tertiaryContainer);
  root.style.setProperty(
    "--on-tertiary-container",
    colors.onTertiaryContainer
  );
  root.style.setProperty("--error-container", colors.errorContainer);
  root.style.setProperty("--on-error", colors.onError);
  root.style.setProperty("--on-error-container", colors.onErrorContainer);
  root.style.setProperty("--md3-outline", colors.outline);
  root.style.setProperty("--outline-variant", colors.outlineVariant);
  root.style.setProperty("--inverse-surface", colors.inverseSurface);
  root.style.setProperty("--inverse-on-surface", colors.inverseOnSurface);
  root.style.setProperty("--inverse-primary", colors.inversePrimary);
  root.style.setProperty("--scrim", colors.scrim);
  root.style.setProperty("--shadow-color", colors.shadow);
  root.style.setProperty("--elevation-1", colors.elevation1);
  root.style.setProperty("--elevation-2", colors.elevation2);
  root.style.setProperty("--elevation-3", colors.elevation3);
}
